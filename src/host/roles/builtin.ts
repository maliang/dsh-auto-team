/** 该 id 是否出厂内置（`source` 判定与「不可删」都由它派生，不看磁盘写了什么）。 */
export function isBuiltinSkill(skillId: string): boolean {
  return BUILTIN_SKILLS.some((skill) => skill.id === skillId)
}

export function builtinSkillBody(skillId: string): string {
  return BUILTIN_SKILLS.find((skill) => skill.id === skillId)?.body ?? ''
}

/**
 * 角色的完整技能正文（注入成员 prompt 时用；未知 skillId 静默跳过并在返回里报告）。
 *
 * `bodyOf` 是 r10 加的**可选解析器**：宿主传 `skills.get(id).body`，让提示词读盘上正文。
 * 不传时退回出厂常量（纯函数单测用）。这一层不是为了好看——用户改过的内置技能
 * 如果不进提示词，界面显示「已修改」而成员行为没变，AC-29 的「重启后读回」就成了假象。
 */
export function composeSkillPrompt(role: Role, bodyOf?: (skillId: string) => string): { text: string; missing: string[] } {
  const parts: string[] = []
  const missing: string[] = []
  for (const skillId of role.skillIds) {
    const resolved = bodyOf === undefined ? undefined : bodyOf(skillId)
    const body = resolved !== undefined && resolved.trim() !== '' ? resolved : builtinSkillBody(skillId)
    if (body === '') {
      missing.push(skillId)
      continue
    }
    parts.push(body)
  }
  return { text: parts.join('\n\n'), missing }
}
